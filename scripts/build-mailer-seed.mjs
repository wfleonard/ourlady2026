#!/usr/bin/env node
// Turns the prewritten campaign emails in docs/email-campaigns/*.md into
// db/mailer-seed.sql, which pm-update applies on every deploy.
//
// The seed is ON CONFLICT DO NOTHING: it adds templates that don't exist yet
// and never overwrites one edited in /admin/mailer/templates. To push a
// changed .md over an existing template, edit it in the UI instead (or delete
// the row and redeploy).
//
//   node scripts/build-mailer-seed.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "docs/email-campaigns");

// file → [segment value a contact carries in its @segment column, slug prefix]
const FILES = {
  "segment-a-guadalupe-parishes.md": ["A", "a"],
  "segment-b-guadalupe-ministries.md": ["B", "b"],
  "segment-c-catholic-schools.md": ["C", "c"],
  "segment-d-diocesan-offices.md": ["D", "d"],
  "holiday-retail-2026.md": ["Retail", "holiday"],
  "novena-drip-2026.md": ["Novena", "novena"],
};

const field = (lines, label) => {
  const prefix = `**${label}:**`;
  const line = lines.find((l) => l.startsWith(prefix));
  return line ? line.slice(prefix.length).trim() : "";
};

const quote = (s) => {
  if (s.includes("$tpl$")) throw new Error("template text contains $tpl$");
  return `$tpl$${s}$tpl$`;
};

const rows = [];
for (const [file, [segment, prefix]] of Object.entries(FILES)) {
  const lines = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").split("\n");
  let n = 0;
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].startsWith("## ")) continue;
    // A section runs to the next "## " heading.
    let end = i + 1;
    while (end < lines.length && !lines[end].startsWith("## ")) end++;
    const section = lines.slice(i + 1, end);
    const bodyAt = section.findIndex((l) => l.trim() === "**Body:**");
    const subject = field(section, "Subject");
    if (bodyAt === -1 || !subject) continue; // notes / variables sections

    const bodyLines = [];
    for (const l of section.slice(bodyAt + 1)) {
      if (l.trim() === "---") break;
      bodyLines.push(l);
    }
    n++;
    rows.push({
      slug: `${prefix}-${n}`,
      name: `${segment} · ${lines[i].slice(3).trim()}`,
      segment,
      position: n,
      subject,
      preview: field(section, "Preview text"),
      body: bodyLines.join("\n").trim(),
    });
  }
}

const sql = [
  "-- GENERATED by scripts/build-mailer-seed.mjs from docs/email-campaigns/*.md.",
  "-- Adds missing templates only; never overwrites edits made in /admin/mailer.",
  "",
  ...rows.map(
    (r) =>
      `INSERT INTO mail_templates (slug, name, segment, position, subject, preview, body) VALUES (\n` +
      `  ${[r.slug, r.name, r.segment].map(quote).join(", ")}, ${r.position},\n` +
      `  ${quote(r.subject)},\n  ${quote(r.preview)},\n  ${quote(r.body)}\n` +
      `) ON CONFLICT (slug) DO NOTHING;\n`
  ),
].join("\n");

writeFileSync(join(root, "db/mailer-seed.sql"), sql);
console.log(`Wrote ${rows.length} templates to db/mailer-seed.sql`);
